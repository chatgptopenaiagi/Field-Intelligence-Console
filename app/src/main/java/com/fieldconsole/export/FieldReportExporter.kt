package com.fieldconsole.export

import android.content.Context
import android.content.Intent
import android.net.Uri
import androidx.core.content.FileProvider
import com.fieldconsole.data.local.entity.FieldEntry
import com.fieldconsole.data.local.entity.WeatherData
import com.fieldconsole.location.GeoContext
import com.google.gson.GsonBuilder
import java.io.File
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale
import javax.inject.Inject
import javax.inject.Singleton

/**
 * FieldReportExporter — generates and shares field reports in multiple formats.
 *
 * Supported formats:
 *  - Markdown (.md)  — structured, human-readable
 *  - JSON (.json)    — machine-readable, suitable for further processing
 *  - Plain Text (.txt) — universal, works everywhere
 */
@Singleton
class FieldReportExporter @Inject constructor() {

    private val dateFmt = SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.getDefault())
    private val fileFmt = SimpleDateFormat("yyyyMMdd_HHmmss", Locale.US)
    private val gson    = GsonBuilder().setPrettyPrinting().create()

    // ── Markdown ──────────────────────────────────────────────────────────────

    fun exportMarkdown(
        context:  Context,
        entry:    FieldEntry,
        geo:      GeoContext,
        weather:  WeatherData? = null
    ) {
        val content = buildMarkdown(entry, geo, weather)
        val fileName = "field_report_${fileFmt.format(Date(entry.timestamp))}.md"
        shareTextFile(context, content, fileName, "text/markdown",
                      "Share Field Report (Markdown)")
    }

    private fun buildMarkdown(entry: FieldEntry, geo: GeoContext, weather: WeatherData?): String =
        buildString {
            appendLine("# Field Intelligence Report")
            appendLine()
            appendLine("**Generated:** ${dateFmt.format(Date(entry.timestamp))}")
            appendLine("**App:** Field Intelligence Console v2")
            appendLine()
            appendLine("---")
            appendLine()
            appendLine("## Location")
            appendLine()
            appendLine("| Field | Value |")
            appendLine("|-------|-------|")
            appendLine("| Place | ${geo.fullPlaceName} |")
            appendLine("| Coordinates | ${geo.coordString} |")
            appendLine("| Accuracy | ±${entry.accuracy.toInt()} m |")
            appendLine("| Maps Link | [Open in Maps](${geo.mapsLink}) |")
            if (geo.country != null) appendLine("| Country | ${geo.country} |")
            appendLine()
            if (entry.note.isNotBlank() || entry.tag.isNotBlank()) {
                appendLine("## Observation")
                appendLine()
                if (entry.note.isNotBlank()) appendLine("**Note:** ${entry.note}")
                if (entry.tag.isNotBlank())  appendLine("**Tag:** `${entry.tag}`")
                if (entry.priority.isNotBlank()) appendLine("**Priority:** ${entry.priority}")
                if (entry.missionId.isNotBlank()) appendLine("**Mission ID:** ${entry.missionId}")
                if (entry.operator.isNotBlank()) appendLine("**Operator:** ${entry.operator}")
                appendLine()
            }
            if (weather != null) {
                appendLine("## Weather Conditions")
                appendLine()
                appendLine("| Parameter | Value |")
                appendLine("|-----------|-------|")
                appendLine("| Conditions | ${weather.weatherDescription} |")
                appendLine("| Temperature | ${weather.tempC.toInt()}°C (feels like ${weather.feelsLikeC.toInt()}°C) |")
                appendLine("| Humidity | ${weather.humidity}% |")
                appendLine("| Wind | ${weather.windSpeedKmh.toInt()} km/h ${bearingLabel(weather.windDirectionDeg)} |")
                appendLine("| Visibility | ${"%.1f".format(weather.visibilityKm)} km |")
                appendLine("| Rain Probability | ${weather.rainProbabilityPct}% |")
                appendLine("| UV Index | ${"%.1f".format(weather.uvIndex)} |")
                appendLine("| Operational Rating | **${weather.operationalRating}** |")
                appendLine()
                appendLine("> ${weather.weatherImpact}")
                appendLine()
            }
            appendLine("---")
            appendLine()
            appendLine("*Report generated by Field Intelligence Console. " +
                       "Location data confirmed by GPS. All analysis is AI inference.*")
        }

    // ── JSON ──────────────────────────────────────────────────────────────────

    fun exportJson(
        context: Context,
        entry:   FieldEntry,
        geo:     GeoContext,
        weather: WeatherData? = null
    ) {
        val data = mapOf(
            "meta" to mapOf(
                "app"       to "Field Intelligence Console v2",
                "generated" to dateFmt.format(Date(entry.timestamp)),
                "version"   to 2
            ),
            "location" to mapOf(
                "latitude"    to entry.latitude,
                "longitude"   to entry.longitude,
                "accuracy_m"  to entry.accuracy,
                "place_name"  to geo.fullPlaceName,
                "street"      to (geo.street ?: ""),
                "district"    to (geo.district ?: ""),
                "city"        to (geo.city ?: ""),
                "country"     to (geo.country ?: ""),
                "maps_link"   to geo.mapsLink,
                "timestamp"   to entry.timestamp
            ),
            "observation" to mapOf(
                "note"       to entry.note,
                "tag"        to entry.tag,
                "priority"   to entry.priority,
                "mission_id" to entry.missionId,
                "operator"   to entry.operator
            ),
            "weather" to if (weather != null) mapOf(
                "description"        to weather.weatherDescription,
                "temp_c"             to weather.tempC,
                "feels_like_c"       to weather.feelsLikeC,
                "humidity_pct"       to weather.humidity,
                "wind_kmh"           to weather.windSpeedKmh,
                "wind_dir_deg"       to weather.windDirectionDeg,
                "visibility_km"      to weather.visibilityKm,
                "rain_probability"   to weather.rainProbabilityPct,
                "uv_index"           to weather.uvIndex,
                "operational_rating" to weather.operationalRating,
                "weather_impact"     to weather.weatherImpact
            ) else null
        )
        val json = gson.toJson(data)
        val fileName = "field_report_${fileFmt.format(Date(entry.timestamp))}.json"
        shareTextFile(context, json, fileName, "application/json",
                      "Share Field Report (JSON)")
    }

    // ── Plain Text ────────────────────────────────────────────────────────────

    fun exportText(
        context: Context,
        entry:   FieldEntry,
        geo:     GeoContext,
        weather: WeatherData? = null
    ) {
        val content = buildPlainText(entry, geo, weather)
        val fileName = "field_report_${fileFmt.format(Date(entry.timestamp))}.txt"
        shareTextFile(context, content, fileName, "text/plain",
                      "Share Field Report")
    }

    private fun buildPlainText(entry: FieldEntry, geo: GeoContext, weather: WeatherData?): String =
        buildString {
            appendLine("=== FIELD INTELLIGENCE REPORT ===")
            appendLine("Generated: ${dateFmt.format(Date(entry.timestamp))}")
            appendLine()
            appendLine("LOCATION")
            appendLine("  Place:       ${geo.fullPlaceName}")
            appendLine("  Coordinates: ${geo.coordString}")
            appendLine("  Accuracy:    ±${entry.accuracy.toInt()} m")
            appendLine("  Maps:        ${geo.mapsLink}")
            appendLine()
            if (entry.note.isNotBlank() || entry.tag.isNotBlank()) {
                appendLine("OBSERVATION")
                if (entry.note.isNotBlank())     appendLine("  Note:        ${entry.note}")
                if (entry.tag.isNotBlank())      appendLine("  Tag:         ${entry.tag}")
                if (entry.priority.isNotBlank()) appendLine("  Priority:    ${entry.priority}")
                if (entry.missionId.isNotBlank())appendLine("  Mission ID:  ${entry.missionId}")
                if (entry.operator.isNotBlank()) appendLine("  Operator:    ${entry.operator}")
                appendLine()
            }
            if (weather != null) {
                appendLine("WEATHER")
                appendLine("  Conditions:  ${weather.weatherDescription}")
                appendLine("  Temperature: ${weather.tempC.toInt()}°C (feels ${weather.feelsLikeC.toInt()}°C)")
                appendLine("  Humidity:    ${weather.humidity}%")
                appendLine("  Wind:        ${weather.windSpeedKmh.toInt()} km/h ${bearingLabel(weather.windDirectionDeg)}")
                appendLine("  Visibility:  ${"%.1f".format(weather.visibilityKm)} km")
                appendLine("  Rain Prob:   ${weather.rainProbabilityPct}%")
                appendLine("  UV Index:    ${"%.1f".format(weather.uvIndex)}")
                appendLine("  Rating:      ${weather.operationalRating}")
                appendLine("  Impact:      ${weather.weatherImpact}")
                appendLine()
            }
            appendLine("Field Intelligence Console v2")
        }

    // ── Share as inline text (no file) ────────────────────────────────────────

    fun shareInlineText(context: Context, entry: FieldEntry, geo: GeoContext, weather: WeatherData? = null) {
        val text = buildPlainText(entry, geo, weather)
        val intent = Intent(Intent.ACTION_SEND).apply {
            type = "text/plain"
            putExtra(Intent.EXTRA_SUBJECT, "Field Report — ${geo.shortLabel}")
            putExtra(Intent.EXTRA_TEXT, text)
        }
        context.startActivity(Intent.createChooser(intent, "Share Field Report"))
    }

    // ── Internal: write to cache and share via FileProvider ──────────────────

    private fun shareTextFile(
        context:   Context,
        content:   String,
        fileName:  String,
        mimeType:  String,
        chooserTitle: String
    ) {
        try {
            val cacheDir = File(context.cacheDir, "reports").also { it.mkdirs() }
            val file = File(cacheDir, fileName)
            file.writeText(content, Charsets.UTF_8)

            val uri: Uri = FileProvider.getUriForFile(
                context,
                "${context.packageName}.provider",
                file
            )
            val intent = Intent(Intent.ACTION_SEND).apply {
                type = mimeType
                putExtra(Intent.EXTRA_STREAM, uri)
                putExtra(Intent.EXTRA_SUBJECT, fileName)
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
            }
            context.startActivity(Intent.createChooser(intent, chooserTitle))
        } catch (e: Exception) {
            // Fallback: share as plain text inline
            val intent = Intent(Intent.ACTION_SEND).apply {
                type = "text/plain"
                putExtra(Intent.EXTRA_TEXT, content)
            }
            context.startActivity(Intent.createChooser(intent, chooserTitle))
        }
    }

    private fun bearingLabel(deg: Int): String {
        val dirs = listOf("N","NE","E","SE","S","SW","W","NW")
        return dirs[((deg + 22.5) / 45).toInt() % 8]
    }
}
